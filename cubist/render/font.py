_BITMAPS = {
    ch: np.array([[c == "#" for c in row] for row in rows], dtype=bool)
    for ch, rows in _GLYPHS.items()
}


def text_width(text: str, scale: int = 1) -> int:
    if not text:
        return 0
    return len(text) * (GLYPH_W + 1) * scale - scale


def text_height(scale: int = 1) -> int:
    return GLYPH_H * scale


def draw_text(canvas: np.ndarray, x: int, y: int, text: str, color, scale: int = 1) -> None:
    """Draw text with its top-left corner at (x, y), clipped to the canvas."""
    h, w = canvas.shape[:2]
    for i, ch in enumerate(text.upper()):
        glyph = _BITMAPS.get(ch, _BITMAPS["?"])
        if scale > 1:
            glyph = np.repeat(np.repeat(glyph, scale, axis=0), scale, axis=1)
        gx = x + i * (GLYPH_W + 1) * scale
        y0, y1 = max(y, 0), min(y + glyph.shape[0], h)
        x0, x1 = max(gx, 0), min(gx + glyph.shape[1], w)
        if y0 >= y1 or x0 >= x1:
            continue
        region = glyph[y0 - y : y1 - y, x0 - gx : x1 - gx]
        canvas[y0:y1, x0:x1][region] = color
